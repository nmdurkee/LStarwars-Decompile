// PC5e3b50: complete bounded ellipse shadow side writer.
using System;
using Recovered.Gameplay;
namespace Recovered.Animation
{
    public static class LegacyEllipseShadows
    {
        struct N
        {
            PlaybackWide value;bool negative;
            public N(float v){value=PlaybackWide.From(v);negative=(PcObjectImage.ToBits(v)&0x80000000u)!=0;}
            static N Make(PlaybackWide v,bool z){double d=v.StoreDouble();return new N{value=v,negative=d<0||(d==0&&z)};}
            public static N operator +(N a,N b){return Make(PlaybackWide.Add(a.value,b.value),a.negative&&b.negative);}
            public static N operator -(N a,N b){return Make(PlaybackWide.Add(a.value,PlaybackWide.Multiply(b.value,PlaybackWide.From(-1))),a.negative&&!b.negative);}
            public static N operator *(N a,N b){return Make(PlaybackWide.Multiply(a.value,b.value),a.negative!=b.negative);}
            public float Store(){float v=value.Store();if(Single.IsInfinity(v)||Single.IsNaN(v))throw new ArgumentException("Finite ellipse output required.");return v==0&&value.StoreDouble()==0?PcObjectImage.FromBits(negative?0x80000000u:0u):v;}
        }
        static void Check(float[] v,int length){if(v==null||v.Length!=length)throw new ArgumentException("Resolved finite vector required.");foreach(float x in v)if(Single.IsNaN(x)||Single.IsInfinity(x))throw new ArgumentException("Finite ellipse input required.");}
        static void U(byte[] b,int p,uint v){b[p]=(byte)v;b[p+1]=(byte)(v>>8);b[p+2]=(byte)(v>>16);b[p+3]=(byte)(v>>24);}
        static void Vertex(LegacyShadowGeometryState state,float[] v,uint color)
        {
            ulong p=(ulong)state.VertexCount*16;if(state.Vertices==null||p+16>(ulong)state.Vertices.Length)throw new ArgumentException("Sufficient output backing required.");
            for(int i=0;i<3;++i)U(state.Vertices,(int)p+i*4,PcObjectImage.ToBits(v[i]));U(state.Vertices,(int)p+12,color);state.VertexCount=unchecked(state.VertexCount+1);
        }
        static float[] Point(float[] ring,float[][] axes,float[] inverse,float[] center)
        {
            var coefficients=new float[3];for(int i=0;i<3;++i)coefficients[i]=((new N(ring[1])*new N(axes[i][1])+new N(ring[0])*new N(axes[i][0])+new N(ring[2])*new N(axes[i][2]))*new N(inverse[i])).Store();
            var result=new float[3];for(int i=0;i<3;++i){float offset=(new N(coefficients[1])*new N(axes[1][i])+new N(coefficients[0])*new N(axes[0][i])+new N(coefficients[2])*new N(axes[2][i])).Store();result[i]=(new N(center[i])+new N(offset)).Store();}return result;
        }
        // Ellipse is12floats: center, then three local axes. Ring is the shared
        //eight rows generated by LegacyShadowConsumer.Prepare. Native upper/lower
        //extra arguments are ignored; color is the separate global2854c00.
        public static void Emit(LegacyShadowGeometryState state,float[] ellipse,float[] matrix,float[] direction,float[][] ring,uint color)
        {
            if(state==null)throw new ArgumentNullException("state");Check(ellipse,12);Check(matrix,16);Check(direction,3);if(ring==null||ring.Length!=8)throw new ArgumentException("Eight ring rows required.");foreach(float[] row in ring)Check(row,3);
            float[] center=LegacyPolygonShadows.TransformPoint(new[]{ellipse[0],ellipse[1],ellipse[2],1f},matrix);var axes=new float[3][];var inverse=new float[3];int[] offsets={6,3,9};
            for(int i=0;i<3;++i)
            {
                var endpoint=new float[4];endpoint[3]=1;for(int j=0;j<3;++j)endpoint[j]=(new N(ellipse[j])+new N(ellipse[offsets[i]+j])).Store();endpoint=LegacyPolygonShadows.TransformPoint(endpoint,matrix);axes[i]=new float[3];for(int j=0;j<3;++j)axes[i][j]=(new N(endpoint[j])-new N(center[j])).Store();
                N x=new N(axes[i][0]),y=new N(axes[i][1]),z=new N(axes[i][2]);float length=BuildEffectSound.SquareRoot((y*y+x*x+z*z).Store());inverse[i]=length==0?0:PlaybackWide.Divide(PlaybackWide.From(1),PlaybackWide.From(length)).Store();
            }
            if(state.GroupCount<250)
            {
                if(state.GroupStarts==null||state.GroupEdgeCounts==null||state.GroupStarts.Length<250||state.GroupEdgeCounts.Length<250)throw new ArgumentException("Two250-entry group arrays required.");state.GroupStarts[state.GroupCount]=state.VertexCount;state.GroupEdgeCounts[state.GroupCount]=8;++state.GroupCount;
            }
            for(int i=0;i<8;++i)
            {
                state.GeneratedValue=unchecked(state.GeneratedValue+2);float[] a=Point(ring[i],axes,inverse,center),b=Point(ring[(i+1)&7],axes,inverse,center);var ea=new float[3];var eb=new float[3];for(int j=0;j<3;++j){ea[j]=(new N(direction[j])*new N(5)+new N(a[j])).Store();eb[j]=(new N(direction[j])*new N(5)+new N(b[j])).Store();}
                Vertex(state,a,color);Vertex(state,ea,color);Vertex(state,eb,color);Vertex(state,b,color);
            }
        }
    }
}
